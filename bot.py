def user_key(msg):
    f = msg.fwd_from
    if f:
        fid = getattr(f, "from_id", None)
        uid = getattr(fid, "user_id", None) if fid else None
        if uid:
            return f"u{uid}"
        if getattr(f, "from_name", None):
            return f"n{f.from_name}"
    return f"s{msg.sender_id}"

AI_ON = True
ADMIN_IDS = [int(x) for x in os.environ.get("ADMIN_IDS", "").split(",") if x.strip()]
LOCKS = {}
LAST = {}

def ask_ai(contents):
    last_err = ""
    for model in MODELS:
        url = f"https://generativelanguage.googleapis.com/v1beta/models/{model}:generateContent"
        headers = {"x-goog-api-key": GEMINI_KEY, "Content-Type": "application/json"}
        body = {
            "system_instruction": {"parts": [{"text": PROMPT}]},
            "contents": contents,
        }
        r = None
        try:
            r = requests.post(url, headers=headers, json=body, timeout=40)
            data = r.json()
            return data["candidates"][0]["content"]["parts"][0]["text"]
        except Exception as e:
            if r is not None:
                last_err = f"{model} -> {r.status_code} {r.text[:200]}"
            else:
                last_err = f"{model} -> {repr(e)}"
            log("AI ERROR:", last_err)
    return "⚠️ AI ERROR: " + last_err

@client.on(events.NewMessage(chats=GROUP_ID))
async def handler(event):
    global AI_ON
    sid = event.sender_id
    text = (event.raw_text or "").strip()
    log("GROUP MSG from:", sid, "|", text[:40])

    me = await client.get_me()

    # /on /off কমান্ড (শুধু মানুষ, বট বা নিজে নয়)
    if text.startswith("/") and sid not in BOT_IDS and sid != me.id:
        if ADMIN_IDS and sid not in ADMIN_IDS:
            return
        cmd = text.split()[0].lower().split("@")[0]
        if cmd in ("/off", "/of"):
            AI_ON = False
            await event.respond("🔕 AI রিপ্লাই বন্ধ। চালু করতে /on লিখুন।")
        elif cmd == "/on":
            AI_ON = True
            await event.respond("🔔 AI রিপ্লাই চালু।")
        return

    if sid not in BOT_IDS:
        return
    if not AI_ON:
        log("AI OFF, skip")
        return
    if not text or text.startswith("/"):
        log("খালি বা কমান্ড, স্কিপ")
        return

    key = user_key(event.message)
    lock = LOCKS.setdefault(key, asyncio.Lock())
    async with lock:
        now = time.time()
        last = LAST.get(key)
        if last and last[0] == text and now - last[1] < 30:
            log("একই মেসেজ, স্কিপ")
            return
        LAST[key] = (text, now)

        if WAIT:
            await asyncio.sleep(WAIT)
            if not AI_ON:
                return
            msgs = await client.get_messages(GROUP_ID, min_id=event.id, limit=50)
            for m in msgs:
                if m.reply_to and m.reply_to.reply_to_msg_id == event.id:
                    log("কেউ রিপ্লাই দিয়েছে, AI স্কিপ")
                    return

        h = HISTORY.get(key)
        if h and now - h["t"] > HIST_TTL:
            h = None
        old = list(h["m"]) if h else []
        contents = old + [{"role": "user", "parts": [{"text": text}]}]
        log("USER KEY:", key, "| history:", len(old))
        reply = await asyncio.to_thread(ask_ai, contents)
        if reply:
            await event.reply(reply)
            log("Replied")
            if not reply.startswith("⚠️ AI ERROR"):
                contents.append({"role": "model", "parts": [{"text": reply}]})
                HISTORY[key] = {"t": now, "m": contents[-MAX_MSGS:]}

class H(BaseHTTPRequestHandler):
    def do_GET(self):
        self.send_response(200); self.end_headers(); self.wfile.write(b"ok")
    def log_message(self, *a): pass

def run_server():
    HTTPServer(("0.0.0.0", int(os.environ.get("PORT", 10000))), H).serve_forever()

async def main():
    log("Connecting to Telegram...")
    await client.connect()
    if not await client.is_user_authorized():
        log("SESSION ERROR: লগইন হয়নি, SESSION বাতিল বা ভুল। নতুন SESSION বানান।")
        return
    await client.get_dialogs()
    me = await client.get_me()
    log("Logged in as:", me.id, me.first_name)
    try:
        await client.send_message(GROUP_ID, "✅ Support 1 চালু হয়েছে")
        log("Start message sent to group")
    except Exception as e:
        log("GROUP ERROR:", repr(e))
    log("Bot running")
    await client.run_until_disconnected()

